#!/usr/bin/env python3
"""Generate src/generated/payloads.S and src/generated/payloads.h from payloads/.

Embeds the Microsoft-signed authenticated UEFI variable payloads (KEK per-PK
updates, 2023 CA db appends, dbx updates) into the GenPE binary via .incbin,
and emits the PK SHA-1 thumbprint -> KEK payload lookup table plus the
SHA-1 thumbprints of the certificates contained in each payload so the tool
can detect already-installed 2023 CAs at runtime.
"""
import hashlib
import json
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAYLOADS = os.path.join(ROOT, "payloads")
OUT_H = os.path.join(ROOT, "src", "generated", "payloads.h")
OUT_S = os.path.join(ROOT, "src", "generated", "payloads.S")

X509_SIGTYPE = bytes.fromhex("a159c0a5e494a74a87b5ab155c2bf072")


def flat(path):
    """payloads/kek uses '__' instead of '/' to keep one flat dir."""
    return path.replace("/", "__")


def read(path):
    with open(os.path.join(PAYLOADS, path), "rb") as f:
        return f.read()


def authvar_content(blob):
    """Return the signature-list payload that follows the AUTH_2 header."""
    (dwlen,) = struct.unpack_from("<I", blob, 16)
    return blob[16 + dwlen:]


def siglist_ders(content):
    """Yield DER certs from an EFI_SIGNATURE_LIST buffer (X509 entries only)."""
    out = []
    off = 0
    while off + 28 <= len(content):
        sigtype = content[off:off + 16]
        lsz, hsz, ssz = struct.unpack_from("<III", content, off + 16)
        if lsz < 28 or off + lsz > len(content):
            break
        ent = off + 28 + hsz
        end = off + lsz
        while ent + ssz <= end and ssz >= 16:
            if sigtype == X509_SIGTYPE:
                out.append(content[ent + 16:ent + ssz])
            ent += ssz
        off += lsz
    return out


def c_bytes(b):
    return ", ".join("0x%02x" % x for x in b)


def main():
    kek_map = json.load(open(os.path.join(PAYLOADS, "kek_map.json")))

    # unique KEK payload paths, stable order
    kek_paths = []
    seen = set()
    for thumb, info in kek_map.items():
        p = info["KEKUpdate"]
        if p not in seen:
            seen.add(p)
            kek_paths.append(p)

    # label every embedded file
    files = []  # (symbol, fs path, logical name)
    for i, p in enumerate(kek_paths):
        files.append(("g_kek_%d" % i, os.path.join("kek", flat(p)), "kek/" + p))
    for sym, fs, name in [
        ("g_db_win2023", "db/DBUpdateWindows2023.bin", "db/windows2023"),
        ("g_db_3p2023", "db/DBUpdate3P2023.bin", "db/3p2023"),
        ("g_db_orom2023", "db/DBUpdateOROM2023.bin", "db/orom2023"),
        ("g_dbx_update", "dbx/DBXUpdate.bin", "dbx/update"),
        ("g_dbx_svn", "dbx/DBXUpdateSVN.bin", "dbx/svn"),
        ("g_dbx_2024", "dbx/DBXUpdate2024.bin", "dbx/2024"),
    ]:
        files.append((sym, os.path.join(*fs.split("/")), name))

    blob = {sym: read(fs) for sym, fs, _ in files}
    bloblen = {sym: len(d) for sym, d in blob.items()}

    # known-certificate table: sha1 of each DER cert inside each payload
    known = []  # (sha1, name) deduped
    kek_index = {}  # thumb -> kek file index

    def add_known(der, name):
        h = hashlib.sha1(der).digest()
        if h not in [k[0] for k in known]:
            known.append((h, name))
        return h

    kek_cert_hashes = set()
    for i, p in enumerate(kek_paths):
        for der in siglist_ders(authvar_content(blob["g_kek_%d" % i])):
            kek_cert_hashes.add(hashlib.sha1(der).digest())
    for h in sorted(kek_cert_hashes):
        known.append((h, "Microsoft Corporation KEK 2K CA 2023"))

    for der in siglist_ders(authvar_content(blob["g_db_win2023"])):
        add_known(der, "Windows UEFI CA 2023")
    for der in siglist_ders(authvar_content(blob["g_db_3p2023"])):
        add_known(der, "Microsoft UEFI CA 2023")
    for der in siglist_ders(authvar_content(blob["g_db_orom2023"])):
        add_known(der, "Microsoft Option ROM UEFI CA 2023")

    idx_of_path = {p: i for i, p in enumerate(kek_paths)}
    entries = []  # (sha1, kek index, path)
    for thumb, info in kek_map.items():
        entries.append((bytes.fromhex(thumb), idx_of_path[info["KEKUpdate"]],
                        info["KEKUpdate"]))
    entries.sort(key=lambda e: e[0])  # sorted by thumb for readability

    # ---- payloads.S ----
    with open(OUT_S, "w", newline="\n") as f:
        f.write("/* generated by tools/embed.py - do not edit */\n")
        f.write('\t.section .rodata\n')
        f.write('\t.balign 16\n')
        for sym, fs, _ in files:
            rel = os.path.join("payloads", fs).replace("\\", "/")
            f.write("\t.global\t%s\n%s:\n\t.incbin\t\"%s\"\n\t.balign 16\n"
                    % (sym, sym, rel))

    # ---- payloads.h ----
    with open(OUT_H, "w", newline="\n") as f:
        f.write("/* generated by tools/embed.py - do not edit */\n")
        f.write("#ifndef GENPE_PAYLOADS_H\n#define GENPE_PAYLOADS_H\n\n")
        for sym, _, _ in files:
            f.write("extern const unsigned char %s[%d];\n" % (sym, bloblen[sym]))
        f.write("\n")

        f.write("typedef struct { unsigned char sha1[20];\n"
                "  const unsigned char *data; unsigned int len;\n"
                "  const char *path; } kek_entry_t;\n")
        f.write("static const kek_entry_t g_kek_map[] = {\n")
        for thumb, i, path in entries:
            f.write("  { { %s }, g_kek_%d, %d, \"%s\" },\n"
                    % (c_bytes(thumb), i, bloblen["g_kek_%d" % i],
                       path.replace("\\", "\\\\").replace('"', '\\"')))
        f.write("};\n#define KEK_MAP_COUNT %d\n\n" % len(entries))

        f.write("typedef struct { unsigned char sha1[20]; const char *name; }"
                " known_cert_t;\n")
        f.write("static const known_cert_t g_known_certs[] = {\n")
        for h, name in known:
            f.write("  { { %s }, \"%s\" },\n" % (c_bytes(h), name))
        f.write("};\n#define KNOWN_CERT_COUNT %d\n\n" % len(known))

        # CA certificate DERs as trust anchors for Authenticode chain
        # verification (point into the embedded payloads, no extra bytes).
        # entries: pointer into a payload, DER length, display name
        f.write("typedef struct { const unsigned char *der; unsigned int len;"
                " const char *name; } ca_cert_t;\n")
        f.write("static const ca_cert_t g_ca_certs[] = {\n")
        seen_der = set()
        for sym, fs, _ in files:
            if not (sym.startswith("g_kek_") or sym.startswith("g_db_")):
                continue
            for der in siglist_ders(authvar_content(blob[sym])):
                h = hashlib.sha1(der).digest()
                if h in seen_der:
                    continue
                seen_der.add(h)
                name = next((n for h2, n in known if h2 == h), None)
                off = blob[sym].find(der)
                f.write("  { %s + %d, %d, %s },\n"
                        % (sym, off, len(der),
                           ("\"%s\"" % name) if name else "NULL"))
        f.write("};\n#define CA_CERT_COUNT %d\n\n" % len(seen_der))

        f.write("typedef struct { const char *name; const unsigned char *data;"
                " unsigned int len; } payload_item_t;\n")
        f.write("static const payload_item_t g_payload_items[] = {\n")
        for sym, _, name in files:
            f.write("  { \"%s\", %s, %d },\n" % (name, sym, bloblen[sym]))
        f.write("};\n#define PAYLOAD_ITEM_COUNT %d\n\n#endif\n"
                % len(files))

    print("wrote %s (%d entries, %d known certs) and %s (%d files, %d bytes)"
          % (OUT_H, len(entries), len(known), OUT_S, len(files),
             sum(bloblen.values())))


if __name__ == "__main__":
    main()
